<#
.SYNOPSIS
  Converts a raw binary file to a C# byte array format.

.DESCRIPTION
  Utility script that reads any binary file (shellcode .bin, PE, etc.) and outputs
  a C# byte array declaration. Useful for converting msfvenom raw output or Donut
  binary output into a format ready to paste into a C# loader.

.EXAMPLE
  .\byte-array-converter.ps1 -InputFile shellcode.bin -OutputFile shellcode.cs

.EXAMPLE
  .\byte-array-converter.ps1 -InputFile payload.bin -OutputFile out.cs -VarName "buf" -BytesPerLine 12
#>
param(
    [Parameter(Mandatory=$true)][string]$InputFile,
    [Parameter(Mandatory=$true)][string]$OutputFile,
    [string]$VarName = "buf",
    [int]$BytesPerLine = 12
)

$bytes = [IO.File]::ReadAllBytes($InputFile)

$lines = @()
$lines += "// Generated by byte-array-converter.ps1"
$lines += "// Source: $InputFile"
$lines += "// Size: $($bytes.Length) bytes"
$lines += "byte[] $VarName = new byte[$($bytes.Length)] {"

for ($i = 0; $i -lt $bytes.Length; $i += $BytesPerLine) {
    $end = [Math]::Min($i + $BytesPerLine - 1, $bytes.Length - 1)
    $hexBytes = ($bytes[$i..$end] | ForEach-Object { "0x{0:X2}" -f $_ }) -join ", "
    $lines += "    $hexBytes,"
}

$lines += "};"

$lines -join "`n" | Set-Content -Path $OutputFile -Encoding ASCII
Write-Host "[+] Wrote $($bytes.Length) bytes to $OutputFile"